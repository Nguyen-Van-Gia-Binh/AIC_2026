import csv
import re

rows = []
for line in raw_data.strip().split("\n"):
    line = line.strip()
    if not line:
        continue
    # Format: rank \t team_raw \t score
    parts = line.split("\t")
    if len(parts) == 3:
        rank_str, team_raw, score_str = parts[0].strip(), parts[1].strip(), parts[2].strip()
    else:
        # Fallback regex
        m = re.match(r"^(\d+)\s+(.+?)\s+([\d,]+)$", line)
        if m:
            rank_str, team_raw, score_str = m.group(1), m.group(2), m.group(3)
        else:
            print("Could not parse line:", line)
            continue
    
    # Try to extract team_name and team_id if in format "Team Name (AIC2026-XXX)"
    # Note: team_name itself can contain parentheses, e.g. Genius And Gay (G.A.Y) (AIC2026-791)
    team_code_match = re.search(r"\((AIC2026-\d+)\)$", team_raw)
    if team_code_match:
        team_id = team_code_match.group(1)
        team_name = team_raw[:team_code_match.start()].strip()
    else:
        team_id = ""
        team_name = team_raw
        
    score_float = float(score_str.replace(",", "."))
    
    rows.append({
        "rank": int(rank_str),
        "team_name": team_name,
        "team_id": team_id,
        "full_team_name": team_raw,
        "score": score_float
    })

print(f"Total parsed rows: {len(rows)}")

# Write to CSV with utf-8-sig
csv_path = "bang_xep_hang_aic2026.csv"
with open(csv_path, "w", newline="", encoding="utf-8-sig") as f:
    writer = csv.DictWriter(f, fieldnames=["rank", "team_name", "team_id", "score", "full_team_name"])
    writer.writeheader()
    writer.writerows(rows)

print(f"Saved to {csv_path}")
