# Load round 1 & round 2
def load_round(filepath, rank_key, score_key):
    data = {}
    try:
        with open(filepath, "r", encoding="utf-8-sig") as f:
            reader = csv.DictReader(f)
            for r in reader:
                key = r["team_id"] if r["team_id"] else r["team_name"]
                data[key] = {
                    rank_key: int(r["rank"]),
                    score_key: float(r["score"]),
                    "team_name": r["team_name"],
                    "team_id": r["team_id"],
                    "full_team_name": r["full_team_name"]
                }
    except Exception as e:
        print(f"Error loading {filepath}: {e}")
    return data

